import {
  AEOLIAN_SCALE_PATTERN,
  DORIAN_SCALE_PATTERN,
  HARMONIC_MINOR_SCALE_PATTERN,
  IONIAN_SCALE_PATTERN,
  LOCRIAN_SCALE_PATTERN,
  LYDIAN_SCALE_PATTERN,
  MAJOR_SCALE_PATTERN,
  MELODIC_MINOR_SCALE_PATTERN,
  MIXOLYDIAN_SCALE_PATTERN,
  NATURAL_MINOR_SCALE_PATTERN,
  PHRYGIAN_SCALE_PATTERN,
  type ScalePattern,
} from "@music-workspace/music-theory";

/** Todos os `ScalePattern` que o app expõe ao usuário — mesma lista usada pelo Scale Explorer. */
export const ALL_SCALE_PATTERNS: ScalePattern[] = [
  MAJOR_SCALE_PATTERN,

  NATURAL_MINOR_SCALE_PATTERN,
  HARMONIC_MINOR_SCALE_PATTERN,
  MELODIC_MINOR_SCALE_PATTERN,

  DORIAN_SCALE_PATTERN,
  AEOLIAN_SCALE_PATTERN,
  IONIAN_SCALE_PATTERN,
  LOCRIAN_SCALE_PATTERN,
  LYDIAN_SCALE_PATTERN,
  MIXOLYDIAN_SCALE_PATTERN,
  PHRYGIAN_SCALE_PATTERN,
];

export function findScalePattern(name: string): ScalePattern {
  return ALL_SCALE_PATTERNS.find((pattern) => pattern.name === name) ?? MAJOR_SCALE_PATTERN;
}
